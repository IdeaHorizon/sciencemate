#: enhancement 成本闸（补丁 6 定案）：次数 / 变体数 / 单次墙钟。
ENHANCE_ATTEMPTS_PER_REQUEST = 2
ENHANCE_MAX_VARIANTS = 3
ENHANCE_CALL_TIMEOUT_S = 120.0
_ENHANCE_ATTEMPTS_KEY = "_enhance_attempts"

#: 环境性失败（栅格化步，按构造在全部内容门之后）不扣铸造预算 —— 预算防的是
#: 内容迭代，环境事故没有迭代价值，图不替机器背锅（2026-10-16 用户拍板）。
#: 但同一请求连续环境失败到上限即熔断：确定性故障重试无意义，停下来如实上报。
_ENV_FAIL_STREAK_KEY = "_env_fail_streak"
_ENV_FAIL_STREAK_LIMIT = 3


def _frozen_svg_script(svg_text: str, png_relpath: str, width_px: int) -> str:
    """铸造时生成的重放脚本（render_code.generator="frozen-svg"）。

    SVG 以字节字面量嵌进脚本 —— render_code 的 content_hash 因此同时绑定
    SVG 源与渲染参数；重放 = 把同一份 SVG 按同一个宽度重新栅格化。
    """
    return (
        '"""Frozen SVG replay: re-rasterize exactly the SVG that was minted.\n\n'
        "Generated by the framework at mint time (generator=frozen-svg). To change\n"
        'the figure, change the contract and the SVG — not this script.\n"""\n'
        "import cairosvg\n\n"
        f"SVG_BYTES = {svg_text.encode('utf-8')!r}\n\n"
        f"cairosvg.svg2png(bytestring=SVG_BYTES, write_to={png_relpath!r}, "
        f"output_width={int(width_px)}, background_color=\"white\")\n"
    )


async def _render_illustration(
    state: Any,
    request_id: str,
    contract_id: str,
    svg_text: str,
    output_name: str | None = None,
    caption: str = "",
    alt_text: str = "",
    trial: bool = False,
    timeout: int = 300,
    **_: Any,
) -> dict[str, Any]:
    """SVG 轨铸造门（trial=true 时是试渲染：同一道审计，不铸记录不占预算）。"""

    attempt: dict[str, Any] | None = None
    try:
        if not svg_text or "<svg" not in svg_text:
            raise VisualContractError("svg_text must be a complete <svg> document")

        policy, caller_request = _bound_policy(state, request_id)
        contract_entry = _contract_store(state).get(contract_id)
        if contract_entry is None:
            raise VisualContractError(
                f"contract_id {contract_id!r} was never declared in this run. "
                f"Declared contracts: {sorted(_contract_store(state)) or '(none)'}. "
                "Call declare_figure_contract first — the contract must exist before "
                "the pixels do."
            )
        if contract_entry.get("request_id") != request_id:
            raise VisualContractError(
                f"contract {contract_id!r} was declared for request "
                f"{contract_entry.get('request_id')!r}, not {request_id!r}: one contract "
                "belongs to one caller request"
            )
        # ── 轨道一致性（方案 A §4.1 第 3 层）：锁定的轨道 vs 源码形态 ──────
        if contract_entry.get("track") != "svg":
            raise VisualContractError(
                f"contract {contract_id!r} is locked to track "
                f"{contract_entry.get('track')!r}, not 'svg': the track was fixed at "
                "declare time from the request's input form. Hand-written SVG only "
                "enters through an svg-track contract."
            )
        contract = contract_entry["contract"]
        if contract["family"] not in ILLUSTRATION_FAMILIES:
            raise VisualContractError(
                f"contract {contract_id!r} is family {contract['family']!r}, not "
                "illustration — SVG minting only accepts illustration contracts"
            )

        from core.project_workspace import validate_tool_cwd

        workspace = validate_tool_cwd(state, None)
        workspace.mkdir(parents=True, exist_ok=True)
        name = slug(output_name or request_id or "illustration")
        medium = contract.get("medium")
        enforce_print = bool(contract_entry.get("enforce_print"))

        # ── 试渲染：审计 + 栅格化 + 摘要，不占预算、不铸记录 ─────────────
        if trial:
            work = workspace / "figure_work"
            work.mkdir(parents=True, exist_ok=True)
            # SVG 先落盘再渲染：栅格化失败（环境性）时创作成果不跟着消失
            # （2026-10-16 e2e 前两轮的教训：bwrap/PIL 事故后 SVG 只存在于
            # transcript 工具参数里，工作区一张图都没有）。
            trial_svg = work / f"{name}.trial.svg"
            trial_svg.write_bytes(svg_text.encode("utf-8"))
            report = await trial_render(
                state,
                svg_text,
                work / f"{name}.trial.png",
                contract=contract,
                policy=policy,
                medium=medium,
                enforce_print=enforce_print,
                timeout=timeout,
            )
            report["svg_path"] = str(trial_svg)
            # 断言预览：mint 门会问的问题，试渲染先问一遍（不占预算的反馈）。
            if report.get("status") == "success":
                preview = evaluate_svg_dom_assertions(
                    contract,
                    dom_nodes=report["observed"]["nodes"],
                    dom_edges=report["observed"]["edges"],
                    dom_groups=report["observed"]["groups"],
                )
                preview_failures = failed_assertions(preview)
                report["assertion_preview"] = preview
                if preview_failures:
                    report["assertion_failures"] = [
                        f"{item['id']} expects {item['comparator']} {item['expected']} "
                        f"but the DOM gives {item['actual']}"
                        for item in preview_failures
                    ]
            return report

        # ── 铸造：预算登记在真的花钱那一刻之前 ───────────────────────────
        attempt = _begin_attempt(state, request_id, contract_id)

        # 机械审计（矛盾级在这里抛 VisualContractError）
        audit = audit_svg(
            svg_text,
            contract=contract,
            policy=policy,
            medium=medium,
            enforce_print=enforce_print,
        )
        # 合同断言对 DOM 求值（与 render_figure 的对象模型对账同尺）
        contract_checks = evaluate_svg_dom_assertions(
            contract,
            dom_nodes=audit["observed"]["nodes"],
            dom_edges=audit["observed"]["edges"],
            dom_groups=audit["observed"]["groups"],
        )
        failures = failed_assertions(contract_checks)
        if failures:
            raise VisualContractError(
                "the SVG contradicts its own contract — assertions evaluated against "
                "the SVG DOM markers: "
                + "; ".join(
                    f"{item['id']} expects {item['comparator']} {item['expected']} "
                    f"but the DOM gives {item['actual']} "
                    f"(from the request: {item['derived_from']!r})"
                    for item in failures
                )
                + ". Fix the SVG markers or the contract, then re-render."
            )

        # 冻结渲染源（SVG 本体）在栅格化**之前**落盘：审计与断言都已通过，
        # 这张图的"绘图结果"此刻已经成立。栅格化若失败（环境性事故），
        # SVG 必须留在盘上、错误里带路径 —— 创作成果不该陪葬（2026-10-16
        # e2e 前两轮：环境事故后工作区一张图都没有，SVG 只存在于 transcript）。
        # 文件名带内容 hash（2026-10-20 审查修复）：同一 output_name 的下一版
        # 不再覆写上一版的冻结证据与交付 PNG —— 旧记录的 replay 与
        # content_hash 永远指得到自己那一份字节；内容相同的重铸幂等同名。
        script_dir = workspace / "figure_src"
        script_dir.mkdir(parents=True, exist_ok=True)
        svg_tag = hash_bytes(svg_text.encode("utf-8"))[7:15]
        frozen_svg = script_dir / f"{name}.{svg_tag}.svg"
        frozen_svg.write_bytes(svg_text.encode("utf-8"))

        png_path = workspace / "figures" / f"{name}.{svg_tag}.png"
        render = await render_svg_png(state, svg_text, png_path, medium=medium, timeout=timeout)
        if render.get("status") == "success" and render.get("tofu"):
            # 渲染器实测豆腐块（cairo 只取 font-family 第一个、无逐字回退）——
            # 内容判决：作者得换字符或换字体。VisualContractError → 照扣预算。
            raise VisualContractError(
                "these characters render as tofu boxes with the fonts the renderer "
                "actually resolves (cairo uses only the FIRST entry of each "
                "font-family list, no per-glyph fallback): "
                + "; ".join(f"{ch!r} via {where}" for ch, where in list(render["tofu"].items())[:8])
                + ". Change the characters, or declare a first font that covers them."
            )
        if render.get("status") != "success":
            # 栅格化在全部内容门（审计 + 断言）之后 —— 这里的失败按构造是环境性的
            # （沙箱起不来 / 渲染器故障），不是图的问题。**不扣铸造预算**：把刚才
            # 登记的尝试从账本撤回（2026-10-16 用户拍板：图不替机器背锅），返回里
            # 机械标注 error_class/budget_charged 供 agent 如实转告调用方。
            history = _attempts(state, request_id)
            if history and history[-1] is attempt:
                history.pop()
            streaks = state.hook_state.setdefault(_ENV_FAIL_STREAK_KEY, {})
            streak = int(streaks.get(request_id, 0)) + 1
            streaks[request_id] = streak
            if streak >= _ENV_FAIL_STREAK_LIMIT:
                return {
                    "status": "error",
                    "error": (
                        f"rasterization failed {streak} times in a row with an "
                        f"environment-level error (latest: {render.get('error')}). "
                        "Retrying a deterministic environment failure is waste — STOP "
                        "re-rendering this request and report the environment problem "
                        "to the caller as-is. The SVG draft is saved at svg_path; "
                        "no render budget was charged."
                    ),
                    "error_class": "environment",
                    "budget_charged": False,
                    "circuit_breaker": "env_fail_streak",
                    "svg_path": str(frozen_svg),
                    "renders_left": _render_budget(state, request_id)[1],
                }
            return {
                **render,
                "error_class": "environment",
                "budget_charged": False,
                "svg_path": str(frozen_svg),
                "note": (
                    "SVG passed the mechanical audit and all contract assertions and "
                    "is saved at svg_path — only rasterization failed (environment). "
                    "No record was minted (the mint gate requires verifiable pixels) "
                    "and no render budget was charged. Report the environment problem "
                    "to the caller; do not try to fix the deployment yourself."
                ),
                "renders_left": _render_budget(state, request_id)[1],
            }
        # 环境失败熔断计数在成功后清零。
        state.hook_state.get(_ENV_FAIL_STREAK_KEY, {}).pop(request_id, None)

        # 冻结重放脚本（render_code 绑定后者，其字节内含 SVG → hash 同时钉住两者）。
        frozen_script = script_dir / f"{name}.{svg_tag}_render.py"
        png_relpath = paths.display_relpath(state, png_path)
        script_text = _frozen_svg_script(svg_text, png_relpath, render["width_px"])
        frozen_script.write_bytes(script_text.encode("utf-8"))
        render_code_hash = hash_bytes(script_text.encode("utf-8"))

        caption = str(caption or "").strip()
        alt_text = str(alt_text or "").strip()
        empty_text_fields = [
            field for field, value in (("caption", caption), ("alt_text", alt_text)) if not value
        ]

        files = [
            {
                "format": "png",
                "path": png_relpath,
                "absolute_path": str(png_path),
                "content_hash": hash_file(png_path),
                "size_bytes": png_path.stat().st_size,
            }
        ]

        # ── findings 装配（与 render_figure 同构）─────────────────────────
        request_findings, _req = _request_findings(state, request_id)
        findings: list[dict[str, Any]] = [*request_findings, *audit["findings"]]
        findings.extend(
            {"collector": "OB-CONTRACT-COVERAGE", **item}
            if "collector" not in item else item
            for item in contract_entry.get("coverage_findings") or []
        )
        if empty_text_fields:
            findings.append(
                {
                    "collector": "OB-CAPTION",
                    "message": (
                        "figure text fields are empty: " + ", ".join(empty_text_fields)
                        + "; recorded as-is (publication paths must supply them)"
                    ),
                    "empty_fields": empty_text_fields,
                }
            )
        # SVG 轨按定义无上游数据 —— 出处缺席必须是可读事实，不是沉默。
        findings.append(
            {
                "collector": "OB-PROVENANCE",
                "message": (
                    "no source artifacts bound: this illustration claims no upstream "
                    "scientific data (expected for the svg track)"
                ),
            }
        )
        previous = _previous_figure_record(state, request_id)
        findings.extend(contract_diff((previous or {}).get("contract"), contract))
        findings.extend(
            check_result_diff((previous or {}).get("contract_checks"), contract_checks)
        )

        brief = caller_request or {"intent": caption or name}
        publication_grade, _exploratory = presentation_defaults(normalize_request(brief))

        # ── VLM 证人（角色在场即跑，缺席如实记）──────────────────────────
        witness_findings, vlm_review = await _witness_review(
            png_path=png_path,
            caption=caption,
            asset_kind=str((caller_request or {}).get("asset_kind") or "generative_illustration"),
            publication_grade=publication_grade,
            contract=contract,
        )
        findings.extend(witness_findings)

        script_relpath = paths.display_relpath(state, frozen_script)
        metadata: dict[str, Any] = {
            "schema_version": FIGURE_SCHEMA_VERSION,
            "record": RENDERED_FIGURE_RECORD,
            "request_id": request_id,
            "asset_kind": str((caller_request or {}).get("asset_kind") or "generative_illustration"),
            "purpose": normalize_request(brief).get("purpose"),
            "source_artifact_ids": [],
            "source_hashes": [],
            "render_code": {
                "path": script_relpath,
                "content_hash": render_code_hash,
                "interpreter": "python3",
                "generator": "frozen-svg",
            },
            "contract": contract,
            "contract_hash": contract_entry.get("contract_hash"),
            "caller_policy": contract_entry.get("policy"),
            "font_floor_pt": contract_entry.get("floor_pt"),
            "layout": None,
            "contract_checks": contract_checks,
            "object_model": None,
            "files": files,
            "caption": caption,
            "alt_text": alt_text,
            "findings": findings,
            # 审计账的形状与 render_figure 对齐：ran 必须真，消费端按它判断
            # 「图像级机械审计跑没跑」（validate_figure_record 的充分性披露）。
            "audit": {"ran": True, "engine": "svg_audit+cairosvg", **audit["summary"]},
            "vlm_review": vlm_review,
            "generative_content": None,
            "replay": {
                "command": ["python3", script_relpath],
                "cwd": paths.display_relpath(state, workspace),
                "requirements": list(RENDER_REQUIREMENTS),
                "note": (
                    "re-running the frozen script re-rasterizes the exact SVG that was "
                    "minted (the SVG bytes are embedded in the script)"
                ),
            },
            # 轨道与文体进 metadata（不进绑定核心 —— 绑定核心泛化，增量字段不碰它）
            "track": "svg",
            "genre": contract_entry.get("genre"),
        }
        metadata["figure_hash"] = figure_binding_hash(metadata)
        reject_verdict_fields(metadata)

        content = f"![{alt_text}]({png_relpath})\n\nCaption: {caption}"
        saved = state.save_artifact(
            artifact_type="figure", name=name, content=content, metadata=metadata
        )
        _note_attempt(
            attempt,
            "success",
            figure_id=saved["id"],
            finding_collectors=sorted(
                {str(item.get("collector") or "") for item in findings} - {""}
            ),
        )
        return {
            "status": "success",
            "figure_id": saved["id"],
            "renders_left": _render_budget(state, request_id)[1],
            "figure_hash": metadata["figure_hash"],
            "files": files,
            "findings": findings,
            "audit": metadata["audit"],
            "vlm_review": vlm_review,
            "contract_checks": contract_checks,
            "replay": metadata["replay"],
        }
    except (VisualContractError, PermissionError, ValueError, OSError, RuntimeError) as exc:
        _note_attempt(attempt, "error", error=str(exc)[:400])
        out: dict[str, Any] = {"status": "error", "error": str(exc)}
        error_code = getattr(exc, "error_code", None)
        if error_code:
            out["error_code"] = error_code
        if not isinstance(exc, VisualContractError):
            # 非内容类失败（IO 事故 / 框架自身的错）：与环境失败同一原则 ——
            # 撤回预算登记，不扣（预算防的是内容迭代；VisualContractError =
            # 审计拒绝/断言不成立/政策闸，才是作者该付费的迭代）。
            history = _attempts(state, request_id)
            if history and history[-1] is attempt:
                history.pop()
            out["error_class"] = "internal"
            out["budget_charged"] = False
        if request_id:
            out["renders_left"] = _render_budget(state, request_id)[1]
        return out
    except Exception:
        # 框架 bug（KeyError 这类不在上面词表里的异常 —— 2026-10-16 e2e 实测：
        # 证人问题生成撞组端点炸 mint，预算照扣、记录没铸）。撤回登记后原样
        # 上抛：registry 的 tool_exception 通道带 traceback，调试信息不丢。
        if attempt is not None:
            history = _attempts(state, request_id)
            if history and history[-1] is attempt:
                history.pop()
        raise


async def _enhance_figure(
    state: Any,
    figure_id: str,
    mode: str = "code2prompt",
    count: int = 1,
    art_style: str | None = None,
    **_: Any,
) -> dict[str, Any]:
    """用图像生成模型美化一张**已铸的 SVG 轨** figure，产物是独立 asset。

    入口闸（补丁 7）：只接受 SVG 轨 figure —— 证据型/数据型图在构造上到不了
    这里（它们的记录 metadata.track != "svg"）。成本三层闸（补丁 6）：次数
    ≤2/request_id、变体 ≤3、单次调用 ≤120s 墙钟；原图永远照常成立，美化失败
    不拖累本体。
    """

    try:
        record = state.read_artifact(figure_id)
        if not isinstance(record, dict):
            raise VisualContractError(f"figure {figure_id!r} does not exist")
        metadata = record.get("metadata") if isinstance(record.get("metadata"), dict) else {}
        if metadata.get("record") != RENDERED_FIGURE_RECORD:
            raise VisualContractError(
                f"{figure_id!r} is not a minted figure record; enhance_figure only "
                "beautifies minted svg-track figures"
            )
        if metadata.get("track") != "svg":
            raise VisualContractError(
                f"enhance_figure only accepts svg-track figures (this one is "
                f"{metadata.get('track') or 'matplotlib/compiled'}): AI beautification of "
                "evidence-bearing or data figures is unreachable by construction — the "
                "pixels would stop being checkable against their source"
            )

        # ── 成本闸 ①：次数（与渲染预算同一个 _attempts 模式）──────────────
        request_id = str(metadata.get("request_id") or figure_id)
        store = state.hook_state.setdefault(_ENHANCE_ATTEMPTS_KEY, {})
        used = int(store.get(request_id) or 0)
        if used >= ENHANCE_ATTEMPTS_PER_REQUEST:
            return {
                "status": "error",
                "error_code": "enhance_budget_exhausted",
                "error": (
                    f"this request has used its {ENHANCE_ATTEMPTS_PER_REQUEST} enhancement "
                    "calls. The minted figure stands as the deliverable; enhancement is "
                    "decoration, not a requirement."
                ),
            }
        store[request_id] = used + 1

        from .. import enhancer

        identity = enhancer.enhancement_identity()
        if identity is None:
            return {
                "status": "not_configured",
                "reason": (
                    "no image-generation identity: neither model_roles 'image_generation' "
                    "nor enhancer_config.yaml + POSTPROCESS_ENHANCEMENT_API_KEY is present. "
                    "The minted figure stands as-is."
                ),
            }

        if mode not in ("none", "code", "code2prompt"):
            raise VisualContractError("mode must be one of none / code / code2prompt")
        count = max(1, min(int(count), ENHANCE_MAX_VARIANTS))

        png_path = next(
            (
                Path(item["absolute_path"])
                for item in metadata.get("files") or []
                if item.get("format") == "png"
            ),
            None,
        )
        if png_path is None or not png_path.is_file():
            raise VisualContractError(f"figure {figure_id!r} has no PNG on disk to enhance")

        # 冻结 SVG（code / code2prompt 模式的技术参照）
        svg_text: str | None = None
        render_code = metadata.get("render_code") or {}
        if render_code.get("path"):
            svg_path = paths.resolve_display_relpath(state, str(render_code["path"]))
            # 冻结的渲染源是 figure_src/{name}.svg，而 render_code.path 是
            # {name}_render.py —— 只换后缀会得到从不存在的 {name}_render.svg
            #（2026-10-20 审查：svg_text 恒 None，code2prompt 静默降级 none）。
            if svg_path.name.endswith("_render.py"):
                svg_path = svg_path.with_name(
                    svg_path.name[: -len("_render.py")] + ".svg"
                )
            else:
                svg_path = svg_path.with_suffix(".svg")
            if svg_path.is_file():
                svg_text = svg_path.read_text(encoding="utf-8")

        # SECTION 3 保留文字**从合同机械抽取**（补丁 5/D11：不让 LLM 从代码里读，
        # 防止 400Gbps 这类标注被图像模型变形）。
        contract = metadata.get("contract") or {}
        keep_text = [text for text in contract_strings(contract) if text.strip()]

        from core.project_workspace import validate_tool_cwd

        workspace = validate_tool_cwd(state, None)
        out_dir = workspace / "figure_enhanced" / slug(figure_id)
        variants: list[dict[str, Any]] = []
        attempts: list[dict[str, Any]] = []
        usage: dict[str, Any] = {}
        effective_modes: list[str] = []
        for index in range(count):
            result = await enhancer.enhance(
                state,
                png_path=png_path,
                svg_text=svg_text,
                mode=mode,
                art_style=art_style,
                out_dir=out_dir,
                keep_text=keep_text,
                timeout_s=ENHANCE_CALL_TIMEOUT_S,
            )
            # 实际执行的模式与降级事实必须进账（enhancer 在返回值里如实带了
            # mode/mode_fallback）——此前只记请求模式，code2prompt 静默降级
            # none 时账上仍写着 code2prompt（2026-10-20 审查）。
            attempt_entry: dict[str, Any] = {
                "index": index,
                "status": result.get("status"),
                "mode": result.get("mode"),
            }
            if result.get("mode_fallback"):
                attempt_entry["mode_fallback"] = result["mode_fallback"]
            attempts.append(attempt_entry)
            if result.get("mode"):
                effective_modes.append(str(result["mode"]))
            if result.get("usage"):
                usage[f"variant_{index}"] = result["usage"]
            if result.get("status") != "success":
                return {
                    "status": "error",
                    "error": result.get("error") or "enhancement failed",
                    "attempts": attempts,
                    "variants": variants,
                    "note": "the minted figure stands as the deliverable; enhancement is optional",
                }
            variants.extend(result.get("variants") or [])

        # ── 产物落账：独立 asset，生成式标记齐全，关联源 figure ─────────────
        files = []
        for variant in variants:
            path = Path(variant["path"])
            files.append(
                {
                    "format": path.suffix.lower().lstrip("."),
                    "path": paths.display_relpath(state, path),
                    "absolute_path": str(path),
                    "content_hash": hash_file(path),
                    "size_bytes": path.stat().st_size,
                }
            )
        asset_metadata: dict[str, Any] = {
            "asset_role": "figure_enhancement",
            "enhanced_from": figure_id,
            "generative_content": {"role": "enhanced_illustration", "evidence_bearing": False},
            "enhancement": {
                "mode": mode,
                "mode_effective": effective_modes[-1] if effective_modes else mode,
                "art_style": art_style,
                # 脱敏形态落账：identity 原件里含 api_key，key 绝不进账本
                #（enhancer._public_identity 的边界，2026-10-20 审查修复）。
                "identity": enhancer._public_identity(identity),
                "usage": usage,
                "attempts": attempts,
                "keep_text_count": len(keep_text),
            },
            "files": files,
            "findings": [
                {
                    "collector": "OB-ENHANCEMENT",
                    "message": (
                        "AI-beautified pixels: text baked into the bitmap was NOT "
                        "mechanically re-checked after enhancement; the minted figure "
                        f"{figure_id} remains the mechanically checked deliverable"
                    ),
                }
            ],
        }
        saved = state.save_artifact(
            artifact_type="asset",
            name=f"{slug(figure_id)}_enhanced",
            content="AI-enhanced variant of " + figure_id,
            metadata=asset_metadata,
        )
        return {
            "status": "success",
            "asset_id": saved["id"],
            "enhanced_from": figure_id,
            "variants": files,
            "usage": usage,
            "findings": asset_metadata["findings"],
            "enhancements_left": ENHANCE_ATTEMPTS_PER_REQUEST - used - 1,
        }
    except (VisualContractError, PermissionError, ValueError, OSError, RuntimeError) as exc:
        return {"status": "error", "error": str(exc)}


