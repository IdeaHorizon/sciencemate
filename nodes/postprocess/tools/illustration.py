"""SVG 轨工具：`render_illustration`（试渲染 + 铸造门）与 `enhance_figure`（可选美化）。

## 这条轨是什么（AutoFigure 移植，方案 A）

纯文字描述的示意图请求（无上游数据、无机器可读 spec）走这里：agent 按
`svg-illustration` skill 手写带 DOM 标记的 SVG（svg_vocab 词表），本工具是
唯一的铸造门：

1. **机械审计**（`svg_audit`：XML/标记/文字政策/字号下限/缺字形，矛盾级拒绝）；
2. **合同 DOM 断言**（`evaluate_svg_dom_assertions`：声明的结构 vs DOM 实际
   标记的结构，不一致拒绝 —— 与 render_figure 的对象模型对账同型同尺）；
3. 渲染 PNG（`svg_render`，cairosvg，沙箱 requirements 装）；
4. VLM 证人 + 出处绑定 + 三重 hash —— 与 render_figure 同一份机制。

试渲染（trial=true）只跑 1+3 并返回轻量审计摘要，**不占渲染预算** ——
mint 前的迭代都走它（方案 A 改进 C9/C10）。

## 纪律

- **不填 annotated_values**（补丁 4）：文字来源的标注数没有 artifact 出处，
  声明了会被 value_check_at_mint 判「够不到出处」拒铸；不声明，缺席被如实
  披露 —— 那是特性。
- 渲染预算与 render_figure 共用同一本账（同一 request_id 合计 ≤3 次铸造）。
- SVG 轨的图是**确定性矢量稿**（合同核过的手写 SVG 栅格化），不是生成式
  像素 —— 不标 generative_content；enhancement 产物才是，走独立 asset。
"""

